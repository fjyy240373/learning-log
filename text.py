# 题目 7：广播的边界
# 初始张量：a7 = torch.arange(6).reshape(2, 3)
# 数值：tensor([[0, 1, 2],
#               [3, 4, 5]])
# 初始张量：b7 = torch.arange(8).reshape(2, 4)
# 数值：tensor([[0, 1, 2, 3],
#               [4, 5, 6, 7]])
# 变换后：a7 + b7
# 广播判断：
# 从右往左对齐维度，如果两个维度相等，或者其中一个是 1，就可以广播。如果既不相等，也没有一个是 1，就会报错。
# 比如：
# a = torch.arange(3).reshape(3, 1)  # 形状 (3, 1)
# b = torch.arange(4).reshape(1, 4)  # 形状 (1, 4)
#  从右往左看：
#  第一维：1 和 4，有一个是 1，可以广播 -> 变成 4
# 第二维：3 和 1，有一个是 1，可以广播 -> 变成 3
#  所以 a + b 会生成一个 (3, 4) 的矩阵，完全没问题！
# 再看一个会报错的：
# a = torch.arange(6).reshape(2, 3)  # 形状 (2, 3)
# b = torch.arange(8).reshape(2, 4)  # 形状 (2, 4)
#  从右往左看：
# 第一维：3 和 4。既不等，也没有 1，无法广播！
#  报错：RuntimeError: The size of tensor a (3) must match the size of tensor b (4) at non-singleton dimension 1
# 预测数值：无
# ==========================================
print("7题: 尝试拼接不兼容的形状 (2,3) 和 (2,4)...")
try:
    a7 = torch.arange(6).reshape(2, 3)
    b7 = torch.arange(8).reshape(2, 4)
    print(a7 + b7)
except RuntimeError as e:
    print("   -> 报错了！原因:", e)

